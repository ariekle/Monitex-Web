"""
Web port of the Hashavshevet (חשבשבת) accounting export — Code VB6/
frmReset1.frm's Public Sub Reset(ResetNr As Long) writes a movein.dat file
whenever a reset is committed OR resent (frmSendtoHash.frm re-running
Reset() against an archived ResetNr<>0, "resend to Hashavshevet").

This module's `build_movein_dat()` implements the SECOND path: regenerating
movein.dat for an ALREADY-ARCHIVED reset (ResetNr<>0), on demand from either
the past-reset lookup screen or the "העברה לחשבשבת" (Transfer to
Hashavshevת) screen — both call routers/reset.py's download_movein_dat().
It reads straight from Invoices/Checks/BadChecks rows already stamped with
that ResetNr — matches the original's re-query (`select * from Invoices
where ResetNr = <n> and Area=<area>`) exactly, since this app's invoice
rows keep their ResetNr permanently once stamped.

WHERE THE FILE ACTUALLY GETS WRITTEN: nowhere on the backend's own
filesystem — the generated bytes are returned as a plain HTTP download.
Confirmed 2026-09-27 that whoever triggers this always does so from a
browser running ON the accounting PC itself (the same machine that then
runs ipus/ipusim to actually import the file into Hashavshevת), so the
browser's own download IS the delivery — no backend-side network push to a
remote machine is needed. (A `write_movein_file()`/file-bridge mechanism
existed briefly for a backend-push scenario that turned out not to apply
here, and was removed.) In practice: point that browser's default download
folder at CFG.hdir's real value (e.g. "C:\hmon12" — the original's own
resend destination, frmReset1.frm ~line 1427-1428) instead of the usual
Downloads folder.

The FIRST path (a brand-new reset, ResetNr=0 at generation time) is NOT
implemented here at all — confirmed 2026-09-27 via frmSendtoHash.frm that
the real workflow never generates movein.dat automatically at commit time
in practice; it's only ever generated on demand, later, through one of the
two screens above. This app's own commit_reset() (routers/reset.py) simply
stamps ResetNr onto the relevant Invoices/Checks rows and stops there.

Reverse-engineered from frmReset1.frm (source stored in CP862/DOS-Hebrew,
confirmed by decoding raw literal bytes) via two research passes
(2026-09-25): one over the movein.dat *print* block (~line 1430-2033), one
over the aggregation logic that feeds it (~line 798-1417).

VALIDATED (2026-09-26) via real byte-diffs against actual old-software
movein.dat exports for two live resets (33727, 33733): all narration
literals (sales, bank name, cash, kupa/hachnasot, delayed-check, bad-check,
credit-note, paid-check-reversal), the header, and every fixed-width field
now match the real export exactly for the record types exercised by those
two resets. Area 9 (Netanya)'s branch name is confirmed to be genuinely
garbled in the REAL old software's own output too (not a bug introduced
here) — see `_SNIF_NAME` below.

ONE INTENTIONAL, KNOWING DEVIATION from the legacy export (approved by the
user 2026-09-26): VAT-rate lookup. See the `act_vat` comment inside
`build_movein_dat()` for the real VB6 source proving the original computes
VAT using the CURRENT/live CFG.VAT rate for every invoice in a reset,
regardless of what rate was actually charged when each invoice was issued —
a real bug in the original whenever VAT changes between an invoice's issue
date and its reset. This app instead uses each invoice's own stored `Vat`
rate, which the user confirmed is the behavior they want going forward,
even though it means this app's export will differ from the legacy one
whenever that specific bug would otherwise have been triggered.

KNOWN, ACCEPTED RESIDUAL DIFFERENCE (investigated 2026-09-26, ResetNr 33733):
isolated per-price-code sales lines can differ from the real legacy export
by exactly 1 agora (always the real export being 1 agora LOWER, never
higher). Root-caused via a debug trace of the real DB rows (not
hand-transcribed data) confirming this is NOT an invoice-inclusion bug and
NOT the VAT-source deviation above -- three independent single-invoice
cases (sub_total 30.0, 55.0, 2150.0, all act_vat=18) were hand-verified
against `temp_vat = Int(sub_total*100*act_vat/(100+act_vat)) / 100; net =
sub_total - temp_vat; Int(net*100)` using plain 64-bit double, 80-bit
extended precision, AND exact decimal arithmetic -- all three agree with
THIS app's output, not the real export's, and no whole-number VAT rate
reproduces the real export's values either. The consistent "-1 agora,
independent of magnitude" pattern is the signature of the original
Intel-x87-FPU 80-bit-extended-register rounding path (historic VB6/native
code on x86) diverging from strict IEEE-754 double arithmetic in a way
that isn't practically reproducible without emulating x87 register
semantics instruction-by-instruction. Accepted as-is per user decision
(2026-09-26) -- this app's arithmetic is, if anything, the more
mathematically correct of the two.

STILL OPEN / NOT YET VALIDATED — record types not exercised by either test
reset so far:

- Three `_SNIF_NAME` values (areas 1/3/6) contain a literal, unrecoverable
  "?" in the VB6 source itself (presumably historical data corruption) —
  reproduced here exactly as found, not guessed at. Areas 2 (Jerusalem) and
  7 (Eilat) were flagged by VB6-source research as having the same kind of
  mixed-codepage literal that turned out to be genuinely garbled for area
  9 — they may exhibit the same real-software garbling, unconfirmed absent
  a real reset from either branch to diff against.
- "מזומן המחאות" (cash-checks deposit summary, record type 4) hasn't
  appeared in either test reset — untested.
- `cash` (record type 7, "מזומן") accumulation on payment_type==1 is
  inferred by analogy to this app's own routers/reset.py (same
  payment_type==1 -> cash pattern used there) since the exact VB6 quote for
  this specific line wasn't captured by either research pass.
- Credit-card payment dates (record type 3) use `main_deposit_date` for
  every payment rather than the original's per-bank/Isracard deposit-cycle
  date tables (init_credit_deposit_dates in frmReset1.frm) — that table's
  exact bank-cycle math wasn't captured either. Only affects the `yymm`/
  `ddmmyy` fields on credit-card lines, not any amount.
- Line-interior padding (the exact count of trailing spaces before a line
  hits 178 chars) is computed here by measuring everything else and padding
  the remainder, rather than copying the VB6 source's literal spacing
  character-for-character in every case — the numeric/GL-account content
  should be right, but padding width inside a field very rarely also
  matters to Hashavshevת parsing, so this is flagged for awareness, not as
  a known bug.

Every emitted line is asserted to be exactly LINE_WIDTH characters before
being added to the file — a bug in any of the fixed-width numeric fields
above will raise instead of silently producing a malformed file.
"""
