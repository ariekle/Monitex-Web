_BANK_NUMBER_CREDIT = 123


def _rj(value: object, width: int) -> str:
    s = str(value)
    if len(s) > width:
        raise ValueError(f"movein.dat field overflow: {value!r} does not fit width {width}")
    return s.rjust(width)


def _vb_str(n: float) -> str:
    """VB6's Str(n) — a leading space for n>=0, none for negative."""
    i = int(n)
    return f" {i}" if i >= 0 else str(i)


def _ddmmyy(d: Optional[date]) -> str:
    return d.strftime("%d%m%y") if d else "000000"


def _yymm(d: Optional[date]) -> str:
    return d.strftime("%y%m") if d else "0000"


def _pad_line(prefix: str) -> str:
    """Pad `prefix` with trailing spaces to exactly LINE_WIDTH, or raise if it's already too long."""
    if len(prefix) > LINE_WIDTH:
        raise ValueError(f"movein.dat line overflow ({len(prefix)} > {LINE_WIDTH}): {prefix!r}")
    line = prefix + " " * (LINE_WIDTH - len(prefix))
    assert len(line) == LINE_WIDTH
    return line


def _parse_slot_date(raw: Optional[str]) -> Optional[date]:
    """
    CheckDateN is usually stored 'DD/MM/YYYY' (matches routers/reset.py's
    _parse_due_date), but the real VB6 source (frmReset1.frm ~line 1228:
    `CDate(Replace(InvRec.Recordset![CheckDate1], ".", "/"))`) normalizes
    '.'-separated dates too -- some older rows apparently use dots.
    Confirmed as a real, live case (2026-09-26): a ResetNr 33631 check with
    a dot-separated CheckDateN silently failed to parse under the
    slash-only version, defaulting to None -> misclassified as a delayed
    check instead of "cash now", which then also emitted the wrong record
    type entirely (record type 5 instead of the cash-checks-summary record
    type 4) -- confirmed via a real byte-diff against the actual
    old-software export for that reset.
    """
    if not raw:
        return None
    normalized = raw.strip().replace(".", "/")
    try:
        return datetime.strptime(normalized, "%d/%m/%Y").date()
    except ValueError:
        return None


def _cc_number(raw: Optional[str]) -> Optional[int]:
    """cc_nr = Mid(CCNrN, 1, 5), card_number = Val(cc_nr)."""
    if not raw:
        return None
    try:
        return int(raw.strip()[:5])
    except ValueError:
        return None


def build_movein_dat(db: Session, reset_row: ResetRow, debug_trace: Optional[list] = None) -> bytes:
    """
    Builds the full movein.dat content for an already-archived reset, as
    CP862 bytes (matches the VB6 source file's own storage encoding — see
    module docstring). Raises ValueError if any field/line width is wrong,
    rather than emitting a malformed file.

    `debug_trace`, if a list is passed in, gets one dict appended per
    Code1-6 line item processed by the cards() loop below — used only by
    the /movein.dat?debug=1 endpoint to get exact ground truth on which
    invoices/amounts feed a given card, instead of hand-transcribing DB
    rows into chat (which is error-prone and was the suspected source of
    an unexplained 1-agora mismatch investigation on 2026-09-26).
    """
    reset_nr = reset_row.ResetNr
    area = reset_row.Area
    main_deposit_date = reset_row.DepositDate or reset_row.ResetDate
    print_date_str = _ddmmyy(reset_row.ResetDate)
    cartis, cartis_delayed = _CARTIS_BY_BANK.get(reset_row.DepoBank, _CARTIS_DEFAULT)

    # DELIBERATE DEVIATION (approved by user 2026-09-26): the real VB6
    # source (frmReset1.frm lines 1019-1020) sets `act_vat` from the
    # GLOBAL, LIVE `VAT` variable (loaded once from CFG.VAT at app
    # startup -- Account.frm: `VAT = cfgRec.Recordset![VAT]`), applying
    # the CURRENT config rate to every invoice in a reset regardless of
    # what rate was actually charged when each invoice was issued:
    #   If EILAT Then act_vat = 0 Else act_vat = VAT
    # This is a real bug in the original if the VAT rate is ever changed
    # between an invoice's issue date and the reset that later reads it --
    # confirmed via a real byte-diff (2026-09-26) showing selective
    # 1-agora mismatches on some price codes but not others in the same
    # reset, consistent with some invoices' snapshotted rate having
    # drifted from the live config. The user confirmed this is a genuine
    # old-software bug and asked this app to compute VAT correctly from
    # each invoice's OWN stored `Vat` rate instead of reproducing it --
    # so, unlike every other quirk in this module, this one is
    # INTENTIONALLY NOT byte-faithful to the legacy export whenever a VAT
    # change is involved.

    invoices = (
        db.query(Invoice)
        .filter(
            Invoice.ResetNr == reset_nr,
            Invoice.Area == area,
            (Invoice.Deleted == False) | (Invoice.Deleted.is_(None)),  # noqa: E712
        )
        .order_by(Invoice.InvNr)
        .all()
    )

    # --- accumulators (all start at 0 — frmReset1.frm lines 898-929) ---
    cards: dict[int, dict] = {}  # Code -> {"acc_number": int|None, "money": float}
    first_inv_number: Optional[int] = None
    last_inv_number = 0
    last_inv_date: Optional[date] = None
    tot_total_kupa = 0.0
    total_credit = 0.0  # gross CREDIT_NOTE total, accumulated in the cards loop
    total_vat = 0.0  # running VAT across the cards loop
    temp_vat_last = 0.0  # last per-line VAT value seen in the cards loop —
    # reproduces the original reading a loop-scratch variable AFTER the loop
    # ends (same read-after-loop pattern already flagged/fixed for
    # ResetPreviewOut.totalVat in routers/reset.py; here it's kept as-is
    # since the goal is byte-fidelity with the legacy export, not a fix).
    cash = 0.0
    credit_card_payments = {0: 0.0, 1: 0.0, 6: 0.0}  # j -> cents; only j in {0,1,6} ever written
    credit_card_numbers: dict[int, Optional[int]] = {0: None, 1: None, 6: None}
    cash_checks_buckets: list[float] = []  # 7-per-bucket, money units (not cents)
    cash_check_running = 0
    delayed_check_lines: list[dict] = []
    paid_check_reversal_lines: list[dict] = []

    for inv in invoices:
        act_vat = 0 if inv.Eilat else (inv.Vat or 0)

        if inv.Type in (HESHBONIT_KABALA, HESHBONIT):
            nr = (inv.InvNr or 0) % 1_000_000
            if first_inv_number is None:
                first_inv_number = nr
            if nr >= last_inv_number:
                last_inv_number = nr
                last_inv_date = inv.Date

        if inv.Type in (HESHBONIT_KABALA, HESHBONIT, CREDIT_NOTE):
            for i in range(1, 7):
                code = getattr(inv, f"Code{i}")
                if not code:
                    # `If Code = 0 Then Exit For` (frmReset1.frm ~line 1135)
                    # -- NOT a "skip this empty slot and keep checking later
                    # ones". The original bails out of the WHOLE per-line
                    # loop the moment it hits a gap, so a later non-empty
                    # slot (e.g. Code3 set while Code1/Code2 are empty)
                    # never gets counted at all. Confirmed as the real cause
                    # of a real byte-diff mismatch (2026-09-26) -- this app
                    # was using `continue` here, which kept scanning past
                    # gaps and double-picked-up line items the original
                    # silently drops.
                    break
                sub_total = getattr(inv, f"SubTotal{i}") or 0
                line_vat = int(sub_total * 100 * act_vat / (100 + act_vat)) / 100 if act_vat else 0.0
                temp_vat_last = line_vat
                net = sub_total - line_vat
                bucket = cards.setdefault(code, {"acc_number": None, "money": 0.0})
                if bucket["acc_number"] is None:
                    # `If Area=7 Then PriceListEilat Else If EILAT Then
                    # PriceListEilat Else PriceList` (frmReset1.frm ~1139) --
                    # checks the invoice's numeric Area against EILAT_AREA
                    # too, not just the Eilat boolean flag alone.
                    use_eilat_table = inv.Area == EILAT_AREA or inv.Eilat
                    price_item = (db.get(PriceListEilat, code) if use_eilat_table else db.get(PriceListItem, code)) or (
                        db.get(PriceListItem, code) or db.get(PriceListEilat, code)
                    )
                    bucket["acc_number"] = getattr(price_item, "AccNr", None) if price_item else None
                if inv.Type == CREDIT_NOTE:
                    bucket["money"] -= net
                    total_credit += sub_total
                    total_vat -= line_vat
                else:
                    bucket["money"] += net
                    tot_total_kupa += sub_total
                    total_vat += line_vat

                if debug_trace is not None:
                    debug_trace.append(
                        {
                            "inv_nr": inv.InvNr,
                            "type": inv.Type,
                            "slot": i,
                            "code": code,
                            "acc_number": bucket["acc_number"],
                            "sub_total": sub_total,
                            "act_vat": act_vat,
                            "line_vat": line_vat,
                            "net": net,
                            "money_running_total": bucket["money"],
                        }
                    )

        if inv.Type in (HESHBONIT_KABALA, KABALA) and (inv.IgnoreInReset or 0) != 1:
            for i in range(1, 7):
                payment_type = getattr(inv, f"PaymentType{i}")
                money = getattr(inv, f"Money{i}") or 0
                if not payment_type:
                    continue
                if payment_type == 1:
                    cash += int(money * 100)
                elif payment_type == 2:
                    raw_check_date = getattr(inv, f"CheckDate{i}")
                    check_date = _parse_slot_date(raw_check_date)
                    is_cash_now = check_date is not None and main_deposit_date is not None and main_deposit_date >= check_date
                    if debug_trace is not None:
                        debug_trace.append(
                            {
                                "kind": "check",
                                "inv_nr": inv.InvNr,
                                "slot": i,
                                "raw_check_date": raw_check_date,
                                "parsed_check_date": check_date.isoformat() if check_date else None,
                                "main_deposit_date": main_deposit_date.isoformat() if main_deposit_date else None,
                                "is_cash_now": is_cash_now,
                                "money": money,
                            }
                        )
                    if is_cash_now:
                        bucket_i = cash_check_running // 7
                        cash_check_running += 1
                        while len(cash_checks_buckets) <= bucket_i:
                            cash_checks_buckets.append(0.0)
                        cash_checks_buckets[bucket_i] += money
                    else:
                        delayed_check_lines.append(
                            {
                                "check_nr": getattr(inv, f"CheckNr{i}") or 0,
                                "inv_nr": inv.InvNr or 0,
                                "check_date": check_date,
                                "money": money,
                            }
                        )
                elif payment_type == 3:
                    credit_card_payments[0] += int(money * 100)
                    credit_card_numbers[0] = _cc_number(getattr(inv, f"CCNr{i}"))
                elif payment_type == 4:
                    credit_card_payments[6] += int(money * 100)
                    credit_card_numbers[6] = _cc_number(getattr(inv, f"CCNr{i}"))
                elif payment_type == 5:
                    credit_card_payments[1] += int(money * 100)
                    credit_card_numbers[1] = _cc_number(getattr(inv, f"CCNr{i}"))

        if inv.Type == KABALA and (inv.IgnoreInReset or 0) == 1:
            org_date = _parse_slot_date(inv.CheckDate2)
            if org_date is not None:
                paid_check_reversal_lines.append(
                    {
                        "check_nr2": inv.CheckNr2 or 0,
                        "taxi_nr": inv.TaxiNr or 0,
                        "family_name": (inv.FamilyName or "").strip(),
                        "org_date": org_date,
                        "money1": inv.Money1 or 0,
                    }
                )
                cash += int((inv.Money1 or 0) * 100)

    if first_inv_number is None:
        first_inv_number = 0
    if last_inv_date is None:
        last_inv_date = reset_row.ResetDate

    tot_total_kupa -= total_credit  # frmReset1.frm line ~1752
    net_total_kupa = sum(int(c["money"] * 100) for c in cards.values())

    lines: list[str] = []

    # --- 1. header ---
    lines.append(_pad_line("  0"))

    # --- 2. per-account sales lines ("סקטינומ תוריכמ") ---
    for entry in cards.values():
        money = entry["money"]
        temp_card = int(money * 100)
        plus = " " if money < 0 else "+"
        acc_number = entry["acc_number"] if entry["acc_number"] is not None else 0
        prefix = (
            "   "
            + _rj(first_inv_number % 100000, 5)
            + print_date_str
            + _rj(last_inv_number % 100000, 5)
            + _ddmmyy(last_inv_date)
            + "  $        "
            + "סקטינומ תוריכמ"
            + " " * 17
            + _rj(acc_number, 7)
            + " " * 32
            + plus
            + _rj(temp_card, 11)
        )
        lines.append(_pad_line(prefix))

    # --- 3. credit-card payment lines ---
    for j in (0, 1, 6):
        money_cents = credit_card_payments[j]
        if money_cents == 0:
            continue
        card_number = credit_card_numbers[j] or 0
        prefix = (
            "   "
            + _rj(card_number, 5)
            + print_date_str
            + _rj(last_inv_number % 100000, 5)
            + _ddmmyy(main_deposit_date)
            + "  $"
            + _rj("הזיו", 22)
            + _rj(_BANK_NUMBER_CREDIT, 4)
            + _yymm(main_deposit_date)
            + " " * 24
            + "+"
            + _rj(int(money_cents), 11)
        )
        lines.append(_pad_line(prefix))

    # --- 4. cash-checks deposit summary lines ---
    for bucket_total in cash_checks_buckets:
        if bucket_total == 0:
            continue
        prefix = (
            "   99999"
            + print_date_str
            + "99999"
            + _ddmmyy(main_deposit_date)
            + "  $          "
            + "תואחמה ןמוזמ"
            + _rj(cartis, 8)
            + " " * 24
            + "+"
            + _rj(int(bucket_total * 100), 11)
        )
        lines.append(_pad_line(prefix))

    # --- 5. delayed-check lines ("יוחד.חמה") ---
    for dc in delayed_check_lines:
        prefix = (
            "   "
            + _rj(dc["check_nr"] % 100000, 5)
            + print_date_str
            + _rj(dc["inv_nr"] % 100000, 5)
            + _ddmmyy(dc["check_date"])
            + "  $"
            + _rj("יוחד.חמה", 22)
            + _rj(cartis_delayed, 4)
            + _yymm(dc["check_date"])
            + " " * 24
            + "+"
            + _rj(int(dc["money"] * 100), 11)
        )
        lines.append(_pad_line(prefix))

    # --- 6. paid-check reversal lines (" רזוח/קש.ש? ... 1100023") ---
    for pr in paid_check_reversal_lines:
        prefix = (
            "   "
            + _rj(pr["check_nr2"] % 100000, 5)
            + print_date_str
            + _rj(pr["taxi_nr"], 5)
            + _ddmmyy(pr["org_date"])
            + "  $"
            + _rj(pr["family_name"][-11:], 11)
            + " רזוח/קש.ש?                 1100023"
            + " " * 33
            + "+"
            + _rj(int(pr["money1"] * 100), 11)
        )
        lines.append(_pad_line(prefix))

    # --- 7. cash deposit line ("מזומן") ---
    if cash > 0:
        prefix = (
            "   "
            + _rj(first_inv_number % 100000, 5)
            + print_date_str
            + _rj(last_inv_number % 100000, 5)
            + _ddmmyy(main_deposit_date)
            + "  $                 "
            + "ןמוזמ "
            + _rj(cartis, 7)
            + " " * 24
            + "+"
            + _rj(_vb_str(cash), 11)
        )
        lines.append(_pad_line(prefix))

    # --- 8/9. kupa + hachnasot-bemaavar lines (only if tot_total_kupa != 0) ---
    if tot_total_kupa != 0:
        plus8 = " " if tot_total_kupa < 0 else "+"
        if area == 7:  # Eilat
            prefix = (
                "   "
                + _rj(first_inv_number % 100000, 5)
                + print_date_str
                + _rj(last_inv_number % 100000, 5)
                + _ddmmyy(last_inv_date)
                + "  $            "
                + "רבעמב הפוק"
                + " 1110021         4520101"
                + "        +"
                + _rj(int(tot_total_kupa * 100), 11)
                + " " * 12
                + plus8
                + _rj(int(tot_total_kupa * 100 - temp_vat_last * 100), 11)
                + "+"
                + _rj(int(temp_vat_last * 100), 11)
            )
            total_vat_for_hachnasot = int(temp_vat_last * 100)
        else:
            total_vat_local = int(temp_vat_last * 100)  # `total_vat = temp_vat * 100` — see module docstring re: this overwrite
            prefix = (
                " לח"
                + _rj(first_inv_number % 100000, 5)
                + print_date_str
                + _rj(last_inv_number % 100000, 5)
                + _ddmmyy(last_inv_date)
                + "  $            "
                + "רבעמב הפוק"
                + " 1110020         4520100"
                + " 3110046+"
                + _rj(int(tot_total_kupa * 100), 11)
                + " " * 12
                + plus8
                + _rj(int(tot_total_kupa * 100) - total_vat_local, 11)
                + "+"
                + _rj(total_vat_local, 11)
            )
            total_vat_for_hachnasot = total_vat_local
        lines.append(_pad_line(prefix))

        plus9 = "+" if tot_total_kupa < 0 else "-"
        if area == 7:
            prefix_a = (
                "   "
                + _rj(first_inv_number % 100000, 5)
                + print_date_str
                + _rj(last_inv_number % 100000, 5)
                + print_date_str
                + "  $            רבעמב הפוק"
                + " 1110021                        "
                + plus9
                + _rj(int(tot_total_kupa * 100), 11)
            )
            lines.append(_pad_line(prefix_a))
            prefix_b = (
                "   "
                + _rj(first_inv_number % 100000, 5)
                + print_date_str
                + _rj(last_inv_number % 100000, 5)
                + _ddmmyy(last_inv_date)
                + "  $          רבעמב תוסנכה                "
                + " 4520101                                "
                + plus9
                + _rj(int(tot_total_kupa * 100), 11)
            )
            lines.append(_pad_line(prefix_b))
        else:
            prefix_a = (
                "   "
                + _rj(first_inv_number % 100000, 5)
                + print_date_str
                + _rj(last_inv_number % 100000, 5)
                + print_date_str
                + "  $            רבעמב הפוק"
                + " 1110020                        "
                + plus9
                + _rj(int(tot_total_kupa * 100), 11)
            )
            lines.append(_pad_line(prefix_a))
            prefix_b = (
                "   "
                + _rj(first_inv_number % 100000, 5)
                + print_date_str
                + _rj(last_inv_number % 100000, 5)
                + _ddmmyy(last_inv_date)
                + "  $          רבעמב תוסנכה                "
                + " 4520100                                "
                + plus9
                + _rj(int(tot_total_kupa * 100) - total_vat_for_hachnasot, 11)
            )
            lines.append(_pad_line(prefix_b))

    # --- 10. per-branch (snif) closing lines — always, regardless of tot_total_kupa ---
    snif_name = _SNIF_NAME.get(area, f"אזור {area}"[:7].rjust(7))
    kupa_snif = _KUPA_SNIF.get(area, 0)
    plus10 = "-" if tot_total_kupa < 0 else "+"
    prefix_a = (
        "   "
        + _rj(first_inv_number % 100000, 5)
        + print_date_str
        + _rj(last_inv_number % 100000, 5)
        + print_date_str
        + "  $          "
        + snif_name
        + " הפוק"
        + _rj(kupa_snif, 8)
        + " " * 24
        + plus10
        + _rj(int(tot_total_kupa * 100), 11)
    )
    lines.append(_pad_line(prefix_a))
    prefix_b = (
        "   "
        + _rj(first_inv_number % 100000, 5)
        + print_date_str
        + _rj(last_inv_number % 100000, 5)
        + print_date_str
        + "  $          "
        + snif_name
        + " הפוק                "
        + _rj(kupa_snif, 8)
        + " " * 32
        + plus10
        + _rj(int(tot_total_kupa * 100), 11)
    )
    lines.append(_pad_line(prefix_b))

    # --- 11. bad-checks lines ("רזוח.חמה") — only Area 0 ---
    if area == 0:
        bad_checks = db.query(BadChecks).filter(BadChecks.ResetNr == reset_nr).order_by(BadChecks.BadCheckNr).all()
        for bc in bad_checks:
            bank_number = 1360005 if (bc.Bank or 0) == 0 else 1300002
            due = _parse_slot_date(bc.DueDate)
            money_cents = int((bc.Money or 0) * 100)
            prefix = (
                "   "
                + _rj((bc.CheckNr or 0) % 100000, 5)
                + print_date_str
                + _rj((bc.TaxiNr or 0) % 100000, 5)
                + _ddmmyy(due)
                + "  $"
                + "           "
                + "   רזוח.חמה 1100023        "
                + _rj(bank_number, 8)
                + "        +"
                + _rj(money_cents, 11)
                + "            +"
                + _rj(money_cents, 11)
            )
            lines.append(_pad_line(prefix))

    # --- 12. credit-note lines ("יוכיז.שח") ---
    for inv in invoices:
        if inv.Type != CREDIT_NOTE:
            continue
        gross = sum(getattr(inv, f"SubTotal{i}") or 0 for i in range(1, 7))
        prefix = (
            "   "
            + _rj((inv.RecNr or 0) % 100000, 5)
            + print_date_str
            + _rj(inv.TaxiNr or 0, 5)
            + _ddmmyy(inv.Date)
            + "  $"
            + "           "
            + "   יוכיז.שח                 3400017                                "
            + "+"
            + _rj(int(gross * 100), 11)
        )
        lines.append(_pad_line(prefix))

    content = "\r\n".join(lines) + "\r\n"
    return content.encode("cp862", errors="replace")
